#include <stdio.h>
/* 
Принципы архитектуры фон Неймана, отраженные в программе:
1. Единая память для команд и данных - массив program[]
2. Последовательное выполнение команд - счётчик pc
3. Принцип хранимой программы - программа как данные в памяти
4. Наличие счётчика команд - переменная pc
*/

int main() {
    // Массив-память с программой и данными
    int program[] = {2, 10, 3, 3, 1, 4, 9, 2, 1, 1, 0};
    
    // Счётчик команд (Program Counter)
    int pc = 0;
    
    // Аккумулятор - регистр для хранения промежуточных результатов
    int acc = 0;
    
    // Главный цикл выполнения (до команды стоп)
    while (1) {
        // Извлечение команды из памяти
        int command = program[pc];
        
        // Обработка команды стоп
        if (command == 0) {
            printf("Выполняется команда 0: стоп\n");
            printf("Итоговое значение acc = %d\n", acc);
            break;
        }
        // Обработка команды вывод
        else if (command == 1) {
            printf("Выполняется команда 1: вывод. acc = %d\n", acc);
            pc = pc + 1; // Переход к следующей команде
        }
        // Обработка команды загрузка
        else if (command == 2) {
            int operand = program[pc + 1]; // Чтение операнда
            acc = operand; // Загрузка числа в аккумулятор
            printf("Выполняется команда 2: загрузка %d. acc = %d\n", operand, acc);
            pc = pc + 2; // Переход через команду и операнд
        }
        // Обработка команды умножение
        else if (command == 3) {
            int operand = program[pc + 1]; // Чтение операнда
            acc = acc * operand; // Умножение аккумулятора
            printf("Выполняется команда 3: умножение на %d. acc = %d\n", operand, acc);
            pc = pc + 2; // Переход через команду и операнд
        }
        // Обработка команды безусловный переход
        else if (command == 4) {
            int address = program[pc + 1]; // Чтение адреса перехода
            printf("Выполняется команда 4: переход на адрес %d\n", address);
            pc = address; // Прямое изменение счётчика команд
        }
        // Обработка неизвестной команды
        else {
            printf("Ошибка: неизвестная команда %d по адресу %d\n", command, pc);
            break;
        }
        
        // Защита от выхода за границы памяти
        if (pc < 0 || pc >= sizeof(program)/sizeof(program[0])) {
            printf("Ошибка: выход за границы памяти по адресу %d\n", pc);
            break;
        }
    }
    return 0;
}